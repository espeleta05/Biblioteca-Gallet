-- SIGEB · Esquema de la base de datos propia (PostgreSQL 14+).
-- Propuesta SIGEB 3.1, nivel 4 ("caja verde"): usuarios, libros, fichas,
-- préstamos, listas de espera, multas y pagos. Diagrama: docs/modelo-datos.md.
-- Ejecutar antes de db/datos-base.sql (y de db/datos-prueba.sql en pruebas). Es idempotente: borra y recrea las tablas.

DROP TABLE IF EXISTS CHATBOT_LOGS, CHATBOT_REGLAS, SOLICITUDES_COMPRA, AVISOS, RECIBOS,
  LISTA_ESPERA, SUSPENSIONES, PAGOS, MULTAS, RENOVACIONES, PRESTAMOS, EJEMPLARES,
  TIPO_CAMBIO, LIBRO_AUTOR, LIBROS, USUARIOS_ESCOLARES, PERSONAL_BIBLIOTECA,
  CREDENCIALES, ROLES, AUTORES, TEMAS, EDITORIALES, BITACORA CASCADE;

-- Gestión de usuarios (Sprint 0) ------------------------------------------

-- Política de préstamo por rol (Reglas 1, 2, 5 y 6). Se configura aquí y no en
-- el código para poder ajustarla sin redeploy.
CREATE TABLE ROLES (
    id_rol           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rol       VARCHAR(30) NOT NULL UNIQUE
                     CHECK (nombre_rol IN ('Administrador','Bibliotecario','Alumno','Profesor','Colaborador')),
    dias_prestamo    INT NOT NULL CHECK (dias_prestamo >= 0),
    max_ejemplares   INT NOT NULL CHECK (max_ejemplares >= 0),
    max_renovaciones INT NOT NULL CHECK (max_renovaciones >= 0)
);

CREATE TABLE CREDENCIALES (
    id_credencial     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol            INT NOT NULL REFERENCES ROLES(id_rol),
    matricula_nomina  VARCHAR(20) NOT NULL UNIQUE,
    contrasena_hash   VARCHAR(255) NOT NULL,
    estatus           VARCHAR(10) NOT NULL DEFAULT 'Activa' CHECK (estatus IN ('Activa','Inactiva')),
    intentos_fallidos INT NOT NULL DEFAULT 0,
    bloqueado_hasta   TIMESTAMP NULL
);

-- Personal de la biblioteca (administradores y bibliotecarios): se da de alta en SIGEB.
CREATE TABLE PERSONAL_BIBLIOTECA (
    id_credencial        INT PRIMARY KEY REFERENCES CREDENCIALES(id_credencial) ON DELETE CASCADE,
    nombre_completo      VARCHAR(150) NOT NULL,
    correo_institucional VARCHAR(100) NOT NULL,
    telefono             VARCHAR(20)
);

-- Alumnos, profesores y colaboradores: copia verificada de la base de datos
-- escolar (integración de solo lectura, Propuesta 3.5). SIGEB no los crea.
CREATE TABLE USUARIOS_ESCOLARES (
    id_credencial        INT PRIMARY KEY REFERENCES CREDENCIALES(id_credencial) ON DELETE CASCADE,
    tipo                 VARCHAR(15) NOT NULL CHECK (tipo IN ('Alumno','Profesor','Colaborador')),
    nombre_completo      VARCHAR(150) NOT NULL,
    correo_institucional VARCHAR(100) NOT NULL,
    telefono             VARCHAR(20),
    activo_en_escuela    BOOLEAN NOT NULL DEFAULT TRUE,
    verificado_en        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Gestionar y buscar libros (Sprint 1) ------------------------------------

CREATE TABLE EDITORIALES (
    id_editorial     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_editorial VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE TEMAS (
    id_tema     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_tema VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE AUTORES (
    id_autor     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_autor VARCHAR(100) NOT NULL UNIQUE
);

-- Ficha bibliográfica. precio_ultima_compra_usd alimenta la Regla 4.
CREATE TABLE LIBROS (
    id_libro                 INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn                     VARCHAR(13) NOT NULL UNIQUE CHECK (isbn ~ '^\d{10}(\d{3})?$'),
    titulo                   VARCHAR(200) NOT NULL,
    id_editorial             INT NOT NULL REFERENCES EDITORIALES(id_editorial),
    id_tema                  INT NOT NULL REFERENCES TEMAS(id_tema),
    edicion                  INT CHECK (edicion > 0),
    anio_publicacion         INT CHECK (anio_publicacion BETWEEN 1450 AND 2100),
    paginas                  INT CHECK (paginas > 0),
    tipo_uso                 VARCHAR(20) NOT NULL DEFAULT 'Préstamo externo'
                             CHECK (tipo_uso IN ('Préstamo externo','Consulta interna','Reservado')),
    precio_ultima_compra_usd NUMERIC(10,2) NOT NULL CHECK (precio_ultima_compra_usd >= 0),
    fecha_registro           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE LIBRO_AUTOR (
    id_libro INT REFERENCES LIBROS(id_libro) ON DELETE CASCADE,
    id_autor INT REFERENCES AUTORES(id_autor),
    PRIMARY KEY (id_libro, id_autor)
);

-- Ejemplar físico: estado y ubicación (existencia y ubicación para "Buscar libros").
CREATE TABLE EJEMPLARES (
    id_ejemplar    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_libro       INT NOT NULL REFERENCES LIBROS(id_libro) ON DELETE RESTRICT,
    clave_ejemplar VARCHAR(30) NOT NULL UNIQUE,
    estado         VARCHAR(12) NOT NULL DEFAULT 'Disponible'
                   CHECK (estado IN ('Disponible','Prestado','Perdido','Robado','Dañado')),
    piso           VARCHAR(20) NOT NULL,
    area           VARCHAR(50) NOT NULL,
    pasillo        VARCHAR(10) NOT NULL,
    estante        VARCHAR(10) NOT NULL
);

-- Solicitud de compra de libros (Product Backlog, Gestionar libros). Solo la
-- solicitud: el proceso del Comprador está excluido (Propuesta 9.3).
CREATE TABLE SOLICITUDES_COMPRA (
    id_solicitud  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_credencial INT NOT NULL REFERENCES CREDENCIALES(id_credencial),
    titulo        VARCHAR(200) NOT NULL,
    autor         VARCHAR(100) NOT NULL,
    isbn          VARCHAR(13) CHECK (isbn IS NULL OR isbn ~ '^\d{10}(\d{3})?$'),
    cantidad      INT NOT NULL DEFAULT 1 CHECK (cantidad > 0),
    justificacion VARCHAR(300) NOT NULL,
    estatus       VARCHAR(12) NOT NULL DEFAULT 'Pendiente' CHECK (estatus IN ('Pendiente','Aprobada','Rechazada')),
    fecha         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Prestar y devolver libros (Sprint 2) ------------------------------------

CREATE TABLE PRESTAMOS (
    id_prestamo       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ejemplar       INT NOT NULL REFERENCES EJEMPLARES(id_ejemplar),
    id_credencial     INT NOT NULL REFERENCES CREDENCIALES(id_credencial),
    id_credencial_registra INT NOT NULL REFERENCES CREDENCIALES(id_credencial),
    fecha_prestamo    DATE NOT NULL,
    fecha_vencimiento DATE NOT NULL,
    fecha_devolucion  DATE NULL,
    condicion_devolucion VARCHAR(12) NULL CHECK (condicion_devolucion IN ('Buen estado','Dañado','Perdido','Robado')),
    estado            VARCHAR(10) NOT NULL DEFAULT 'Activo' CHECK (estado IN ('Activo','Devuelto'))
);

CREATE TABLE RENOVACIONES (
    id_renovacion              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_prestamo                INT NOT NULL REFERENCES PRESTAMOS(id_prestamo),
    id_credencial_autoriza     INT NOT NULL REFERENCES CREDENCIALES(id_credencial),
    fecha_renovacion           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_vencimiento_anterior DATE NOT NULL,
    fecha_vencimiento_nueva    DATE NOT NULL
);

CREATE TABLE LISTA_ESPERA (
    id_espera          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_libro           INT NOT NULL REFERENCES LIBROS(id_libro) ON DELETE CASCADE,
    id_credencial      INT NOT NULL REFERENCES CREDENCIALES(id_credencial),
    fecha_solicitud    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado             VARCHAR(12) NOT NULL DEFAULT 'En espera' CHECK (estado IN ('En espera','Notificado','Atendido','Cancelado')),
    fecha_notificacion TIMESTAMP NULL
);
-- Una persona no puede estar dos veces en espera del mismo libro.
CREATE UNIQUE INDEX ux_lista_espera_activa ON LISTA_ESPERA (id_libro, id_credencial) WHERE estado IN ('En espera','Notificado');

-- Gestión de multas y alumnos suspendidos (Sprint 3) ----------------------

CREATE TABLE TIPO_CAMBIO (
    fecha     DATE PRIMARY KEY,
    valor_mxn NUMERIC(10,4) NOT NULL CHECK (valor_mxn > 0),
    fuente    VARCHAR(30) NOT NULL DEFAULT 'Banxico SIE SF43718'
);

CREATE TABLE MULTAS (
    id_multa          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_prestamo       INT NOT NULL REFERENCES PRESTAMOS(id_prestamo),
    id_credencial     INT NOT NULL REFERENCES CREDENCIALES(id_credencial),
    motivo            VARCHAR(10) NOT NULL CHECK (motivo IN ('Retraso','Daño','Pérdida','Robo')),
    monto_mxn         NUMERIC(10,2) NOT NULL CHECK (monto_mxn >= 0),
    dias_retraso      INT NULL,
    tipo_cambio       NUMERIC(10,4) NULL,
    estatus           VARCHAR(10) NOT NULL DEFAULT 'Pendiente' CHECK (estatus IN ('Pendiente','Pagada','Revocada')),
    fecha_generacion  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    motivo_revocacion VARCHAR(255) NULL,
    id_credencial_revoca INT NULL REFERENCES CREDENCIALES(id_credencial),
    aviso_tesoreria   BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE PAGOS (
    id_pago              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_multa             INT NOT NULL UNIQUE REFERENCES MULTAS(id_multa),
    monto_pagado_mxn     NUMERIC(10,2) NOT NULL CHECK (monto_pagado_mxn > 0),
    referencia_tesoreria VARCHAR(60) NOT NULL,
    id_credencial_registra INT NOT NULL REFERENCES CREDENCIALES(id_credencial),
    fecha_pago           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE SUSPENSIONES (
    id_suspension        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_credencial        INT NOT NULL REFERENCES CREDENCIALES(id_credencial),
    causa                VARCHAR(20) NOT NULL CHECK (causa IN ('Exceso de multas','Robo','Mal uso')),
    detalle              VARCHAR(255) NOT NULL,
    origen               VARCHAR(10) NOT NULL CHECK (origen IN ('Automática','Manual')),
    fecha_inicio         DATE NOT NULL,
    fecha_fin            DATE NULL,
    estado               VARCHAR(10) NOT NULL DEFAULT 'Activa' CHECK (estado IN ('Activa','Levantada')),
    aviso_servicios_escolares BOOLEAN NOT NULL DEFAULT FALSE
);

-- Notificaciones (correo, WhatsApp, impresión) ----------------------------

-- Recibos de préstamo y de pago (evidencia ISO 9001).
CREATE TABLE RECIBOS (
    folio         VARCHAR(20) PRIMARY KEY,
    tipo          VARCHAR(10) NOT NULL CHECK (tipo IN ('Préstamo','Pago')),
    id_referencia INT NOT NULL,
    id_credencial INT NOT NULL REFERENCES CREDENCIALES(id_credencial),
    contenido     TEXT NOT NULL,
    fecha         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Registro de cada envío: recibos, avisos de adeudo y avisos de lista de espera.
CREATE TABLE AVISOS (
    id_aviso      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_credencial INT NOT NULL REFERENCES CREDENCIALES(id_credencial),
    tipo          VARCHAR(20) NOT NULL CHECK (tipo IN ('Recibo de préstamo','Recibo de pago','Aviso de adeudo','Lista de espera')),
    canal         VARCHAR(10) NOT NULL CHECK (canal IN ('Correo','WhatsApp','Impresión')),
    destino       VARCHAR(120) NOT NULL,
    mensaje       TEXT NOT NULL,
    estado        VARCHAR(12) NOT NULL CHECK (estado IN ('Enviado','Simulado','Fallido')),
    detalle_envio VARCHAR(255) NULL,
    fecha         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Chatbot (Sprint 4) ------------------------------------------------------

-- Base de conocimiento validada con la Biblioteca (reglas y políticas).
CREATE TABLE CHATBOT_REGLAS (
    id_regla             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tema                 VARCHAR(30) NOT NULL CHECK (tema IN ('Vigencias','Renovaciones','Multas','Costos de reposición','Préstamos')),
    pregunta_frecuente   VARCHAR(255) NOT NULL,
    palabras_clave       VARCHAR(255) NOT NULL,
    respuesta_bot        TEXT NOT NULL,
    ultima_actualizacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE CHATBOT_LOGS (
    id_log             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_credencial      INT NOT NULL REFERENCES CREDENCIALES(id_credencial),
    pregunta_usuario   TEXT NOT NULL,
    intencion          VARCHAR(40) NOT NULL,
    respuesta_generada TEXT NOT NULL,
    motor              VARCHAR(20) NOT NULL,
    fecha_hora         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Trazabilidad (ISO 9001:2015: "cada operación queda registrada") ---------

CREATE TABLE BITACORA (
    id_evento     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    servicio      VARCHAR(30) NOT NULL,
    accion        VARCHAR(60) NOT NULL,
    detalle       VARCHAR(500) NOT NULL,
    id_credencial INT NULL REFERENCES CREDENCIALES(id_credencial),
    fecha_hora    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Índices para las consultas frecuentes (RNF: respuesta ≤ 3 s) ------------
CREATE INDEX ix_ejemplares_libro_estado ON EJEMPLARES (id_libro, estado);
CREATE INDEX ix_prestamos_usuario_estado ON PRESTAMOS (id_credencial, estado);
CREATE INDEX ix_prestamos_vencimiento_activos ON PRESTAMOS (fecha_vencimiento) WHERE estado = 'Activo';
CREATE INDEX ix_multas_usuario_estatus ON MULTAS (id_credencial, estatus);
CREATE INDEX ix_suspensiones_activas ON SUSPENSIONES (id_credencial) WHERE estado = 'Activa';
CREATE INDEX ix_libros_titulo ON LIBROS (lower(titulo));
CREATE INDEX ix_bitacora_fecha ON BITACORA (fecha_hora DESC);
