DROP TABLE IF EXISTS CHATBOT_LOGS;
DROP TABLE IF EXISTS CHATBOT_REGLAS;
DROP TABLE IF EXISTS DETALLE_COMPRA;
DROP TABLE IF EXISTS COMPRAS;
DROP TABLE IF EXISTS SOLICITUDES_ADQUISICION;
DROP TABLE IF EXISTS PRESUPUESTOS;
DROP TABLE IF EXISTS LISTA_ESPERA;
DROP TABLE IF EXISTS SUSPENSIONES;
DROP TABLE IF EXISTS PAGOS;
DROP TABLE IF EXISTS MULTAS;
DROP TABLE IF EXISTS RENOVACIONES;
DROP TABLE IF EXISTS PRESTAMOS;
DROP TABLE IF EXISTS EJEMPLARES;
DROP TABLE IF EXISTS TIPO_CAMBIO;
DROP TABLE IF EXISTS LIBRO_AUTOR;
DROP TABLE IF EXISTS LIBROS;
DROP TABLE IF EXISTS ALUMNOS;
DROP TABLE IF EXISTS PROFESORES;
DROP TABLE IF EXISTS PERSONAL_BIBLIOTECA;
DROP TABLE IF EXISTS CREDENCIALES;
DROP TABLE IF EXISTS ROLES_PERMISOS;
DROP TABLE IF EXISTS AUTORES;
DROP TABLE IF EXISTS TEMAS;
DROP TABLE IF EXISTS EDITORIALES;
DROP TABLE IF EXISTS PERMISOS;
DROP TABLE IF EXISTS ROLES;

CREATE TABLE ROLES (
    id_rol INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rol VARCHAR(50) NOT NULL,
    dias_prestamo INT NOT NULL,
    max_ejemplares INT NOT NULL,
    max_renovaciones INT NOT NULL
);

CREATE TABLE PERMISOS (
    id_permiso INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_permiso VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(255)
);

CREATE TABLE ROLES_PERMISOS (
    id_rol INT NOT NULL,
    id_permiso INT NOT NULL,
    PRIMARY KEY (id_rol, id_permiso),
    FOREIGN KEY (id_rol) REFERENCES ROLES(id_rol) ON DELETE CASCADE,
    FOREIGN KEY (id_permiso) REFERENCES PERMISOS(id_permiso) ON DELETE CASCADE
);

CREATE TABLE CREDENCIALES (
    id_credencial INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol INT NOT NULL,
    matricula_nomina VARCHAR(20) NOT NULL UNIQUE,
    contrasena_hash VARCHAR(255) NOT NULL,
    estatus VARCHAR(20) NOT NULL DEFAULT 'Activa',
    intentos_fallidos INT NOT NULL DEFAULT 0,
    bloqueado_hasta TIMESTAMP NULL,
    FOREIGN KEY (id_rol) REFERENCES ROLES(id_rol)
);

CREATE TABLE ALUMNOS (
    matricula VARCHAR(20) PRIMARY KEY,
    id_credencial INT NOT NULL UNIQUE,
    nombre_completo VARCHAR(150) NOT NULL,
    correo_institucional VARCHAR(100) NOT NULL,
    telefono VARCHAR(15),
    FOREIGN KEY (id_credencial) REFERENCES CREDENCIALES(id_credencial) ON DELETE CASCADE
);

CREATE TABLE PROFESORES (
    nomina VARCHAR(20) PRIMARY KEY,
    id_credencial INT NOT NULL UNIQUE,
    nombre_completo VARCHAR(150) NOT NULL,
    correo_institucional VARCHAR(100) NOT NULL,
    telefono VARCHAR(15),
    FOREIGN KEY (id_credencial) REFERENCES CREDENCIALES(id_credencial) ON DELETE CASCADE
);

CREATE TABLE PERSONAL_BIBLIOTECA (
    id_personal INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_credencial INT NOT NULL UNIQUE,
    nomina VARCHAR(20) NOT NULL UNIQUE,
    nombre_completo VARCHAR(150) NOT NULL,
    correo_institucional VARCHAR(100),
    puesto VARCHAR(50) NOT NULL,
    FOREIGN KEY (id_credencial) REFERENCES CREDENCIALES(id_credencial) ON DELETE CASCADE
);

CREATE TABLE EDITORIALES (
    id_editorial INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_editorial VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE TEMAS (
    id_tema INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_tema VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE AUTORES (
    id_autor INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_autor VARCHAR(100) NOT NULL
);

CREATE TABLE LIBROS (
    id_libro VARCHAR(13) PRIMARY KEY,
    isbn VARCHAR(13) NOT NULL UNIQUE,
    titulo VARCHAR(150) NOT NULL,
    id_editorial INT,
    id_tema INT,
    edicion INT,
    paginas INT,
    tipo_uso VARCHAR(30) NOT NULL,
    precio_ultima_compra_usd DECIMAL(10,2),
    FOREIGN KEY (id_editorial) REFERENCES EDITORIALES(id_editorial),
    FOREIGN KEY (id_tema) REFERENCES TEMAS(id_tema)
);

CREATE TABLE LIBRO_AUTOR (
    id_libro VARCHAR(13),
    id_autor INT,
    PRIMARY KEY (id_libro, id_autor),
    FOREIGN KEY (id_libro) REFERENCES LIBROS(id_libro) ON DELETE CASCADE,
    FOREIGN KEY (id_autor) REFERENCES AUTORES(id_autor) ON DELETE CASCADE
);

CREATE TABLE EJEMPLARES (
    id_ejemplar INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_libro VARCHAR(13) NOT NULL,
    clave_ejemplar VARCHAR(50) NOT NULL UNIQUE,
    estado VARCHAR(20) NOT NULL DEFAULT 'Disponible',
    piso VARCHAR(20),
    area VARCHAR(50),
    pasillo VARCHAR(50),
    estante VARCHAR(50),
    FOREIGN KEY (id_libro) REFERENCES LIBROS(id_libro) ON DELETE RESTRICT
);

CREATE TABLE TIPO_CAMBIO (
    id_tipo_cambio INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL UNIQUE,
    valor_mxn DECIMAL(10,2) NOT NULL
);

CREATE TABLE PRESTAMOS (
    id_prestamo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ejemplar INT NOT NULL,
    id_credencial INT NOT NULL,
    fecha_prestamo TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_vencimiento DATE NOT NULL,
    fecha_devolucion TIMESTAMP NULL,
    estado VARCHAR(15) NOT NULL DEFAULT 'Activo',
    FOREIGN KEY (id_ejemplar) REFERENCES EJEMPLARES(id_ejemplar),
    FOREIGN KEY (id_credencial) REFERENCES CREDENCIALES(id_credencial)
);

CREATE TABLE RENOVACIONES (
    id_renovacion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_prestamo INT NOT NULL,
    id_credencial_autoriza INT NOT NULL,
    fecha_renovacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_vencimiento_anterior DATE NOT NULL,
    fecha_vencimiento_nueva DATE NOT NULL,
    FOREIGN KEY (id_prestamo) REFERENCES PRESTAMOS(id_prestamo) ON DELETE CASCADE,
    FOREIGN KEY (id_credencial_autoriza) REFERENCES CREDENCIALES(id_credencial)
);

CREATE TABLE MULTAS (
    id_multa INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_prestamo INT NOT NULL,
    id_credencial INT NOT NULL,
    monto_mxn DECIMAL(10,2) NOT NULL,
    motivo VARCHAR(20) NOT NULL,
    estatus VARCHAR(20) NOT NULL DEFAULT 'Pendiente',
    fecha_generacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (id_prestamo) REFERENCES PRESTAMOS(id_prestamo),
    FOREIGN KEY (id_credencial) REFERENCES CREDENCIALES(id_credencial)
);

CREATE TABLE PAGOS (
    id_pago INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_multa INT NOT NULL UNIQUE,
    monto_pagado_mxn DECIMAL(10,2) NOT NULL,
    referencia_tesoreria VARCHAR(100),
    fecha_pago TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (id_multa) REFERENCES MULTAS(id_multa)
);

CREATE TABLE SUSPENSIONES (
    id_suspension INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_credencial INT NOT NULL,
    motivo VARCHAR(255) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NULL,
    estado VARCHAR(15) NOT NULL DEFAULT 'Activa',
    FOREIGN KEY (id_credencial) REFERENCES CREDENCIALES(id_credencial)
);

CREATE TABLE LISTA_ESPERA (
    id_espera INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_libro VARCHAR(13) NOT NULL,
    id_credencial INT NOT NULL,
    fecha_solicitud TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado VARCHAR(20) NOT NULL DEFAULT 'En espera',
    FOREIGN KEY (id_libro) REFERENCES LIBROS(id_libro),
    FOREIGN KEY (id_credencial) REFERENCES CREDENCIALES(id_credencial)
);

CREATE TABLE PRESUPUESTOS (
    id_presupuesto INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mes INT NOT NULL,
    anio INT NOT NULL,
    monto_asignado_mxn DECIMAL(10,2) NOT NULL,
    monto_utilizado_mxn DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    UNIQUE(mes, anio)
);

CREATE TABLE SOLICITUDES_ADQUISICION (
    id_solicitud INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_credencial INT NOT NULL,
    titulo_sugerido VARCHAR(150) NOT NULL,
    autor_sugerido VARCHAR(100),
    cantidad_sugerida INT NOT NULL DEFAULT 1,
    estatus VARCHAR(20) NOT NULL DEFAULT 'Pendiente',
    fecha_solicitud TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (id_credencial) REFERENCES CREDENCIALES(id_credencial)
);

CREATE TABLE COMPRAS (
    id_compra INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_presupuesto INT NOT NULL,
    id_editorial INT NOT NULL,
    folio VARCHAR(50) NOT NULL UNIQUE,
    fecha_orden DATE NOT NULL,
    total_mxn DECIMAL(10,2) NOT NULL,
    estatus VARCHAR(30) NOT NULL DEFAULT 'Registrada',
    FOREIGN KEY (id_presupuesto) REFERENCES PRESUPUESTOS(id_presupuesto),
    FOREIGN KEY (id_editorial) REFERENCES EDITORIALES(id_editorial)
);

CREATE TABLE DETALLE_COMPRA (
    id_detalle INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compra INT NOT NULL,
    id_libro VARCHAR(13) NOT NULL,
    cantidad INT NOT NULL,
    precio_unitario_usd DECIMAL(10,2) NOT NULL,
    FOREIGN KEY (id_compra) REFERENCES COMPRAS(id_compra) ON DELETE CASCADE,
    FOREIGN KEY (id_libro) REFERENCES LIBROS(id_libro)
);

CREATE TABLE CHATBOT_REGLAS (
    id_regla INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tema VARCHAR(50) NOT NULL,
    pregunta_frecuente VARCHAR(255) NOT NULL,
    respuesta_bot TEXT NOT NULL,
    ultima_actualizacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE CHATBOT_LOGS (
    id_log INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_credencial INT NOT NULL,
    id_regla INT NULL,
    pregunta_usuario TEXT NOT NULL,
    respuesta_generada TEXT NOT NULL,
    fecha_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (id_credencial) REFERENCES CREDENCIALES(id_credencial),
    FOREIGN KEY (id_regla) REFERENCES CHATBOT_REGLAS(id_regla)
);

CREATE TABLE ACTIVIDAD_SISTEMA (
    id_actividad INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(20) NOT NULL,
    titulo VARCHAR(150) NOT NULL,
    detalle VARCHAR(255) NOT NULL,
    fecha_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);